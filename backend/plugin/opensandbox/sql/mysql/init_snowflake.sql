create table if not exists sys_opensandbox (
    id bigint not null primary key,
    sandbox_id varchar(64) not null,
    name varchar(128) not null,
    image varchar(512) not null,
    user_id bigint not null,
    username varchar(64) not null,
    status varchar(16) not null default 'Pending',
    last_activity_time datetime(6) not null default now(6),
    paused_time datetime(6),
    expires_at datetime(6),
    created_time datetime(6) not null default now(6),
    updated_time datetime(6),
    deleted bigint not null default 0,
    deleted_time datetime(6),
    unique key uk_sys_opensandbox_sandbox_id (sandbox_id),
    key ix_sys_opensandbox_user_id (user_id),
    key ix_sys_opensandbox_status (status),
    key ix_sys_opensandbox_last_activity (last_activity_time)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='OpenSandbox 沙盒归属与活动记录';

create table if not exists sys_opensandbox_command (
    id bigint not null primary key,
    sandbox_id varchar(64) not null,
    sandbox_name varchar(128) not null,
    user_id bigint not null,
    username varchar(64) not null,
    source varchar(16) not null,
    session_id varchar(128),
    command longtext not null,
    cwd varchar(512),
    stdout longtext not null,
    stderr longtext not null,
    exit_code integer,
    status varchar(16) not null default 'success',
    duration_ms integer not null default 0,
    truncated tinyint(1) not null default 0,
    created_time datetime(6) not null default now(6),
    updated_time datetime(6),
    deleted bigint not null default 0,
    deleted_time datetime(6),
    key ix_sys_opensandbox_command_sandbox (sandbox_id),
    key ix_sys_opensandbox_command_user (user_id),
    key ix_sys_opensandbox_command_status (status),
    key ix_sys_opensandbox_command_time (created_time)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_unicode_ci comment='OpenSandbox 命令执行审计日志';
